import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';
const require = createRequire(import.meta.url), ts = require('typescript');
const path = 'src/features/mock-exams/question-model.ts';
assert.ok(existsSync(path), 'Short-answer public model must exist');
const module = { exports: {} };
vm.runInNewContext(ts.transpileModule(readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module, exports: module.exports });
const m = module.exports;
assert.equal(m.normalizeShortAnswer('  hình\u00a0\tchữ  nhật '), 'hình chữ nhật');
assert.notEqual(m.normalizeShortAnswer('0,5'), m.normalizeShortAnswer('0.5'));
assert.notEqual(m.normalizeShortAnswer('A'), m.normalizeShortAnswer('a'));
assert.equal(m.normalizeShortAnswer('\u2003a\u2003'), '\u2003a\u2003');
const legacy = { id: 'q1', content: '?', options: ['a', 'b'], diagram: null, correct_answer: 1 };
const short = { id: 'q2', question_type: 'short_answer', content: '?', options: [], diagram: null, accepted_answers: ['secret'] };
const questions = m.parseExamQuestions([legacy, short]);
assert.equal(questions[0].question_type, 'multiple_choice');
assert.equal(questions[0].correct_answer, undefined);
assert.equal(questions[1].accepted_answers, undefined);
assert.equal(m.parseExamQuestions([legacy, legacy]), null);
assert.equal(m.parseExamQuestions([{ ...short, question_type: 'essay' }]), null);
assert.equal(m.parseExamQuestions([{ ...short, question_type: null }]), null);
assert.equal(m.parseExamQuestions([{ ...short, options: ['bad'] }]), null);
assert.equal(m.isExamAnswerPresent(questions[0], 0), true);
assert.equal(m.isExamAnswerPresent(questions[1], ' \t\u00a0'), false);
assert.equal(m.isExamAnswerPresent(questions[1], '😀'.repeat(100)), true);
assert.equal(m.isExamAnswerPresent(questions[1], '😀'.repeat(101)), false);
const answers = m.validExamAnswers(questions, JSON.parse('{"q1":0,"q2":"<img src=x onerror=alert(1)>","outside":1,"__proto__":1}'));
assert.equal(JSON.stringify(answers), JSON.stringify({ q1: 0, q2: '<img src=x onerror=alert(1)>' }));
assert.equal(Object.hasOwn(answers, '__proto__'), false);
console.log('PASS: public question union, legacy MCQ, literal normalization, Unicode limits, scoped answers and private-key stripping.');
